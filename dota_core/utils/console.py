def print_section_header(title: str, icon: str = "📊", width: int = 80, color: str = Colors.BRIGHT_CYAN):
    """
    Печатает заголовок главной секции с двойной линией сверху и снизу,
    центрированным текстом и декоративными иконками.

    Формат вывода:
    ════════════════════════════════════════
    📊 ЗАГОЛОВОК СЕКЦИИ 📊 (центрировано)
    ════════════════════════════════════════

    Args:
        title (str): Текст заголовка
        icon (str, optional): Декоративная иконка. По умолчанию "📊"
        width (int, optional): Ширина рамки в символах. По умолчанию 80
        color (str, optional): ANSI код цвета. По умолчанию Colors.BRIGHT_CYAN

    Note:
        Функция автоматически добавляет отступ сверху для визуального разделения
    """
    print(f"\n{color}{'═' * width}{Colors.RESET}")

    # Центрируем заголовок с иконками по ширине рамки
    centered_title = f"{icon} {title} {icon}".center(width)
    print(f"{color}{centered_title}{Colors.RESET}")

    print(f"{color}{'═' * width}{Colors.RESET}")


def print_subsection_header(title: str, icon: str = "▶", color: str = Colors.BRIGHT_YELLOW):
    """
    Печатает заголовок подсекции с одинарным подчеркиванием.

    Формат вывода:
    ▶ Заголовок подсекции
    ─────────────────────

    Args:
        title (str): Текст заголовка подсекции
        icon (str, optional): Декоративная иконка. По умолчанию "▶"
        color (str, optional): ANSI код цвета. По умолчанию Colors.BRIGHT_YELLOW
    """
    print(f"\n{color}{icon} {Colors.BOLD}{title}{Colors.RESET}")

    # Подчеркивание длиной равной заголовку + иконка + пробелы
    underline_length = len(title) + 3  # +3 за иконку и пробелы
    print(f"{color}{'─' * underline_length}{Colors.RESET}")


def print_info_line(label: str, value: str, icon: str = "•",
                    label_color: str = Colors.BRIGHT_WHITE,
                    value_color: str = Colors.BRIGHT_GREEN):
    """
    Печатает информационную строку в формате "иконка метка: значение"
    с настраиваемыми цветами для каждого элемента.

    Формат вывода:
      • Метка: значение

    Args:
        label (str): Название параметра или метки
        value (str): Значение параметра
        icon (str, optional): Иконка перед строкой. По умолчанию "•"
        label_color (str, optional): ANSI код цвета метки. По умолчанию Colors.BRIGHT_WHITE
        value_color (str, optional): ANSI код цвета значения. По умолчанию Colors.BRIGHT_GREEN
    """
    print(f"  {icon} "
          f"{label_color}{label}:{Colors.RESET} "
          f"{value_color}{value}{Colors.RESET}")


def print_progress_bar(current: int, total: int, prefix: str = "", width: int = 40,
                       fill_color: str = Colors.BRIGHT_GREEN, empty_color: str = Colors.DIM):
    """
    Печатает прогресс-бар в виде заполняемой полосы с процентами и счетчиками.

    Формат вывода:
      Префикс [████████████░░░░░░░░] 60.5% (605/1000)

    Args:
        current (int): Текущее значение прогресса
        total (int): Максимальное значение
        prefix (str, optional): Текст перед прогресс-баром. По умолчанию ""
        width (int, optional): Ширина бара в символах. По умолчанию 40
        fill_color (str, optional): ANSI код цвета заполненной части (█).
            По умолчанию Colors.BRIGHT_GREEN
        empty_color (str, optional): ANSI код цвета пустой части (░).
            По умолчанию Colors.DIM

    Note:
        - При total=0 процент устанавливается в 0 для избежания деления на ноль
        - Процент ограничен 100% даже если current > total
    """
    # Безопасное вычисление процента
    if total == 0:
        percentage = 0
        filled_length = 0
    else:
        # Ограничиваем процент максимумом 100%
        percentage = min(100.0, (current / total) * 100)
        filled_length = min(width, int(width * current // total))

    # Создаем визуальный бар из заполненных и пустых символов
    bar = (f"{fill_color}{'█' * filled_length}"
           f"{empty_color}{'░' * (width - filled_length)}{Colors.RESET}")

    print(f"  {Colors.BRIGHT_WHITE}{prefix}{Colors.RESET} "
          f"{Colors.BRIGHT_WHITE}[{bar}{Colors.RESET}] "
          f"{Colors.BRIGHT_YELLOW}{percentage:.1f}%{Colors.RESET} "
          f"({Colors.BRIGHT_WHITE}{current:,}/{total:,}{Colors.RESET})")


def print_status_message(message: str, status: str = "info", icon: str = ""):
    """
    Печатает статусное сообщение с автоматической цветовой кодировкой и иконки в зависимости
    от типа статуса. Поддерживает стандартные типы статусов или кастомные
    иконки для специальных случаев.

    Args:
        message (str): Текст сообщения
        status (str, optional): Тип статуса. Варианты:
            - "success": зеленый цвет, иконка ✅
            - "error": красный цвет, иконка ❌
            - "warning": желтый цвет, иконка ⚠️
            - "info": синий цвет, иконка ℹ️
            По умолчанию "info"
        icon (str, optional): Кастомная иконка, переопределяет стандартную

    Note:
        При неизвестном статусе используется белый цвет и символ "•"
    """
    # Словарь соответствия статусов и цветов
    status_colors = {
        "success": Colors.BRIGHT_GREEN,
        "error": Colors.BRIGHT_RED,
        "warning": Colors.BRIGHT_YELLOW,
        "info": Colors.BRIGHT_BLUE
    }

    # Словарь стандартных иконок для каждого статуса
    status_icons = {
        "success": "✅",
        "error": "❌",
        "warning": "⚠️",
        "info": "ℹ️"
    }

    # Получаем цвет для статуса
    color = status_colors.get(status, Colors.BRIGHT_WHITE)

    # Используем кастомную или стандартную иконку для статуса
    status_icon = icon or status_icons.get(status, "•")

    print(f"{color}{status_icon} {message}{Colors.RESET}")
