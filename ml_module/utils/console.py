"""
Модуль утилит для форматированного вывода в консоль.

Предоставляет набор функций и констант для создания элегантного
пользовательского интерфейса в терминале с использованием ANSI escape-кодов.

Основные возможности:
- Расширенная палитра цветов (базовые, яркие, 256-цветные)
- Стили текста (жирный, курсив, подчеркивание и др.)
- Заголовки секций и подсекций
- Информационные строки с иконками
- Прогресс-бары с настраиваемым внешним видом
- Статусные сообщения с цветовой кодировкой

Модуль разработан для улучшения читаемости консольного вывода
в программах сбора и обработки данных.
"""


class Colors:
    """
    Расширенная палитра ANSI цветов и стилей для элегантного форматированного вывода.

    Класс содержит константы ANSI escape-кодов, организованные по категориям:
    - Основные цвета (8 базовых цветов)
    - Яркие цвета (8 ярких версий базовых цветов)
    - Специальные стили (жирный, курсив, подчеркивание и др.)
    - Цвета фона (8 базовых цветов фона)
    - 256-цветная палитра (расширенные цвета)
    - Яркие версии расширенных цветов

    Все коды совместимы с большинством современных терминалов,
    поддерживающих ANSI escape-последовательности.
    """

    # === ОСНОВНЫЕ ЦВЕТА (8 базовых цветов) ===
    BLACK = '\033[30m'      # Черный
    RED = '\033[31m'        # Красный
    GREEN = '\033[32m'      # Зеленый
    YELLOW = '\033[33m'     # Желтый
    BLUE = '\033[34m'       # Синий
    MAGENTA = '\033[35m'    # Пурпурный
    CYAN = '\033[36m'       # Голубой
    WHITE = '\033[37m'      # Белый

    # === ЯРКИЕ ЦВЕТА (интенсивные версии базовых цветов) ===
    BRIGHT_BLACK = '\033[90m'      # Яркий черный (серый)
    BRIGHT_RED = '\033[91m'        # Яркий красный
    BRIGHT_GREEN = '\033[92m'      # Яркий зеленый
    BRIGHT_YELLOW = '\033[93m'     # Яркий желтый
    BRIGHT_BLUE = '\033[94m'       # Яркий синий
    BRIGHT_MAGENTA = '\033[95m'    # Яркий пурпурный
    BRIGHT_CYAN = '\033[96m'       # Яркий голубой
    BRIGHT_WHITE = '\033[97m'      # Яркий белый

    # === СПЕЦИАЛЬНЫЕ СТИЛИ ===
    BOLD = '\033[1m'           # Жирный текст
    DIM = '\033[2m'            # Приглушенный текст
    ITALIC = '\033[3m'         # Курсивный текст
    UNDERLINE = '\033[4m'      # Подчеркнутый текст
    BLINK = '\033[5m'          # Мигающий текст
    REVERSE = '\033[7m'        # Инвертированные цвета
    STRIKETHROUGH = '\033[9m'  # Зачеркнутый текст

    # === ЦВЕТА ФОНА ===
    BG_BLACK = '\033[40m'      # Черный фон
    BG_RED = '\033[41m'        # Красный фон
    BG_GREEN = '\033[42m'      # Зеленый фон
    BG_YELLOW = '\033[43m'     # Желтый фон
    BG_BLUE = '\033[44m'       # Синий фон
    BG_MAGENTA = '\033[45m'    # Пурпурный фон
    BG_CYAN = '\033[46m'       # Голубой фон
    BG_WHITE = '\033[47m'      # Белый фон

    # === 256-ЦВЕТНАЯ ПАЛИТРА (дополнительные цвета) ===
    ORANGE = '\033[38;5;208m'      # Оранжевый
    PURPLE = '\033[38;5;129m'      # Фиолетовый
    PINK = '\033[38;5;205m'        # Розовый
    LIME = '\033[38;5;154m'        # Лаймовый
    GOLD = '\033[38;5;220m'        # Золотой
    SILVER = '\033[38;5;250m'      # Серебряный
    CORAL = '\033[38;5;203m'       # Коралловый
    TEAL = '\033[38;5;37m'         # Бирюзовый
    LAVENDER = '\033[38;5;183m'    # Лавандовый
    MINT = '\033[38;5;121m'        # Мятный

    # === ЯРКИЕ ВЕРСИИ ДОПОЛНИТЕЛЬНЫХ ЦВЕТОВ ===
    BRIGHT_ORANGE = '\033[38;5;214m'      # Яркий оранжевый
    BRIGHT_PURPLE = '\033[38;5;135m'      # Яркий фиолетовый
    BRIGHT_PINK = '\033[38;5;213m'        # Яркий розовый
    BRIGHT_LIME = '\033[38;5;155m'        # Яркий лаймовый
    BRIGHT_GOLD = '\033[38;5;226m'        # Яркий золотой
    BRIGHT_SILVER = '\033[38;5;255m'      # Яркий серебряный
    BRIGHT_CORAL = '\033[38;5;210m'       # Яркий коралловый
    BRIGHT_TEAL = '\033[38;5;51m'         # Яркий бирюзовый
    BRIGHT_LAVENDER = '\033[38;5;189m'    # Яркий лавандовый
    BRIGHT_MINT = '\033[38;5;122m'        # Яркий мятный

    # === СБРОС ФОРМАТИРОВАНИЯ ===
    RESET = '\033[0m'  # Сброс всех стилей и цветов к значениям по умолчанию


def print_section_header(title: str, icon: str = "📊", width: int = 80, color: str = Colors.BRIGHT_CYAN):
    """
    Печатает заголовок главной секции с рамкой из символов.

    Создает визуально выделенный заголовок с двойной линией сверху и снизу,
    центрированным текстом и декоративными иконками. Используется для
    обозначения основных разделов программы.

    Args:
        title (str): Текст заголовка
        icon (str, optional): Декоративная иконка. По умолчанию "📊"
        width (int, optional): Ширина рамки в символах. По умолчанию 80
        color (str, optional): ANSI код цвета. По умолчанию Colors.BRIGHT_CYAN

    Note:
        Функция автоматически добавляет отступ сверху для визуального разделения
    """
    # Добавляем отступ сверху для визуального разделения секций
    print(f"\n{color}{'═' * width}{Colors.RESET}")

    # Центрируем заголовок с иконками по ширине рамки
    centered_title = f"{icon} {title} {icon}".center(width)
    print(f"{color}{centered_title}{Colors.RESET}")

    # Нижняя граница секции
    print(f"{color}{'═' * width}{Colors.RESET}")


def print_subsection_header(title: str, icon: str = "▶", color: str = Colors.BRIGHT_YELLOW):
    """
    Печатает заголовок подсекции с подчеркиванием.

    Создает менее выделенный заголовок для подразделов внутри основных секций.
    Использует одинарную линию подчеркивания и стиль жирного текста.

    Args:
        title (str): Текст заголовка подсекции
        icon (str, optional): Декоративная иконка. По умолчанию "▶"
        color (str, optional): ANSI код цвета. По умолчанию Colors.BRIGHT_YELLOW

    Note:
        Длина подчеркивания автоматически рассчитывается по длине заголовка
    """
    # Добавляем отступ сверху и выводим заголовок с жирным шрифтом
    print(f"\n{color}{icon} {Colors.BOLD}{title}{Colors.RESET}")

    # Подчеркивание длиной равной заголовку + иконка + пробелы
    underline_length = len(title) + 3  # +3 за иконку и пробелы
    print(f"{color}{'─' * underline_length}{Colors.RESET}")


def print_info_line(label: str, value: str, icon: str = "•",
                    label_color: str = Colors.BRIGHT_WHITE,
                    value_color: str = Colors.BRIGHT_GREEN,
                    icon_color: str = Colors.BRIGHT_BLUE):
    """
    Печатает информационную строку с цветным форматированием.

    Создает структурированный вывод в формате "иконка метка: значение"
    с настраиваемыми цветами для каждого элемента. Используется для
    отображения ключевых параметров и статистики.

    Args:
        label (str): Название параметра или метки
        value (str): Значение параметра
        icon (str, optional): Иконка перед строкой. По умолчанию "•"
        label_color (str, optional): Цвет метки. По умолчанию Colors.BRIGHT_WHITE
        value_color (str, optional): Цвет значения. По умолчанию Colors.BRIGHT_GREEN
        icon_color (str, optional): Цвет иконки. По умолчанию Colors.BRIGHT_BLUE
    """
    # Форматируем строку с отступом, цветной иконкой, меткой и значением
    print(f"  {icon_color}{icon}{Colors.RESET} "
          f"{label_color}{label}:{Colors.RESET} "
          f"{value_color}{value}{Colors.RESET}")


def print_progress_bar(current: int, total: int, prefix: str = "", width: int = 40,
                       fill_color: str = Colors.BRIGHT_GREEN, empty_color: str = Colors.DIM):
    """
    Печатает настраиваемый прогресс-бар с процентами и счетчиками.

    Создает визуальный индикатор прогресса в виде заполняемой полосы
    с процентным соотношением и числовыми значениями. Поддерживает
    настройку цветов заполненной и пустой частей.

    Args:
        current (int): Текущее значение прогресса
        total (int): Максимальное значение (цель)
        prefix (str, optional): Текст перед прогресс-баром. По умолчанию ""
        width (int, optional): Ширина бара в символах. По умолчанию 40
        fill_color (str, optional): Цвет заполненной части. По умолчанию Colors.BRIGHT_GREEN
        empty_color (str, optional): Цвет пустой части. По умолчанию Colors.DIM

    Note:
        - При total=0 процент устанавливается в 0 для избежания деления на ноль
        - Процент ограничен максимумом 100% даже если current > total
        - Использует символы █ для заполненной части и ░ для пустой
    """
    # Безопасное вычисление процента (избегаем деления на ноль)
    if total == 0:
        percentage = 0
    else:
        # Ограничиваем процент максимумом 100%
        percentage = min(100.0, (current / total) * 100)

    # Вычисляем количество заполненных символов
    filled_length = int(width * current // total) if total > 0 else 0

    # Создаем визуальный бар из заполненных и пустых символов
    bar = (f"{fill_color}{'█' * filled_length}"
           f"{empty_color}{'░' * (width - filled_length)}{Colors.RESET}")

    # Выводим полную строку с префиксом, баром, процентами и счетчиками
    print(f"  {prefix} [{bar}] "
          f"{Colors.BRIGHT_YELLOW}{percentage:.1f}%{Colors.RESET} "
          f"({Colors.BRIGHT_WHITE}{current:,}/{total:,}{Colors.RESET})")


def print_status_message(message: str, status: str = "info", icon: str = ""):
    """
    Печатает статусное сообщение с соответствующей цветовой кодировкой.

    Выводит сообщение с автоматическим выбором цвета и иконки в зависимости
    от типа статуса. Поддерживает стандартные типы статусов или кастомные
    иконки для специальных случаев.

    Args:
        message (str): Текст сообщения
        status (str, optional): Тип статуса. Варианты:
            - "success": Зеленый цвет, иконка ✅
            - "error": Красный цвет, иконка ❌
            - "warning": Желтый цвет, иконка ⚠️
            - "info": Синий цвет, иконка ℹ️
            По умолчанию "info"
        icon (str, optional): Кастомная иконка (переопределяет стандартную)

    Note:
        - Если указана кастомная иконка, она используется вместо стандартной
        - При неизвестном статусе используется белый цвет и символ "•"
    """
    # Словарь соответствия статусов и цветов
    status_colors = {
        "success": Colors.BRIGHT_GREEN,
        "error": Colors.BRIGHT_RED,
        "warning": Colors.BRIGHT_YELLOW,
        "info": Colors.BRIGHT_BLUE
    }

    # Словарь стандартных иконок для каждого статуса
    status_icons = {
        "success": "✅",
        "error": "❌",
        "warning": "⚠️",
        "info": "ℹ️"
    }

    # Получаем цвет для статуса (или белый по умолчанию)
    color = status_colors.get(status, Colors.BRIGHT_WHITE)

    # Используем кастомную иконку или стандартную для статуса
    status_icon = icon or status_icons.get(status, "•")

    # Выводим цветное сообщение с иконкой
    print(f"{color}{status_icon} {message}{Colors.RESET}")
