"""
Настройки Telegram-бота.

Переменные окружения для всей системы читаются в dota_core.config, поэтому его
импорт здесь гарантирует, что .env уже загружен к моменту чтения os.getenv ниже.
"""

# Стандартные библиотеки
import os

# Сторонние библиотеки
import telebot

# Локальные импорты
import dota_core.config  # noqa: F401


# ────────────────────────────────────────────────────────────────────────────
# Backend API
# ────────────────────────────────────────────────────────────────────────────

# Базовый адрес backend. Полные адреса запросов строятся от него в api_client.
API_BASE_URL = os.getenv('API_BASE_URL')


# ────────────────────────────────────────────────────────────────────────────
# Telegram
# ────────────────────────────────────────────────────────────────────────────

# Токен бота, выданный BotFather.
TELEGRAM_BOT_TOKEN = os.getenv('TELEGRAM_BOT_TOKEN')

# Чат или канал, куда публикуются матчи. Для каналов Telegram использует идентификатор вида "-100...".
TELEGRAM_CHAT_ID = os.getenv('TELEGRAM_CHAT_ID')

# Единственный экземпляр бота на весь процесс.
BOT = telebot.TeleBot(TELEGRAM_BOT_TOKEN)


# ────────────────────────────────────────────────────────────────────────────
# Публикация
# ────────────────────────────────────────────────────────────────────────────

# Порог уверенности прогноза, при котором матч публикуется:
#   None  — публиковать все матчи без отбора.
#   float — публиковать только при уверенном прогнозе в любую сторону, то есть
#           predict_win >= threshold или predict_win <= 1 - threshold.
#           Например, 0.60 пропускает матчи с вероятностью победы ≥60% или ≤40%.
PUBLISH_WIN_THRESHOLD = None


# ────────────────────────────────────────────────────────────────────────────
# Статистика
# ────────────────────────────────────────────────────────────────────────────

# Какие отчёты публиковать в Telegram.
STATS_DAILY_ENABLED = True
STATS_WEEKLY_ENABLED = True
STATS_MONTHLY_ENABLED = True

# Параметры симуляции ставок в отчётах.
FIXED_BID = 1000     # Размер фиксированной ставки, ₽
BANK_SIZE = 10000    # Стартовый банк для процентной стратегии, ₽
FIX_PERCENT = 10     # Доля банка в одной ставке, %

# Время запуска отчётов относительно часового пояса сервера (HH:MM).
STATS_RUN_AT = "04:00"
